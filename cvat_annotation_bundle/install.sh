#!/usr/bin/env bash
# One-step CVAT installer for the YOLOv8 segmentation annotation workflow.
set -euo pipefail

bundle_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cvat_dir="${bundle_root}/cvat"
min_compose_version="2.24.4"  # first release that understands `!override`
datasets=()
bind_address="127.0.0.1"
cvat_host="localhost"
mirror=""
install_docker=0
create_admin="ask"
original_args=("$@")

usage() {
  cat <<'EOF'
Usage: install.sh [options]

  --dataset DIR        Mount a YOLO dataset read-only as a CVAT connected file
                       share (repeatable). Appears as /<basename of DIR>.
  --lan HOST_OR_IP     Listen on all interfaces and serve CVAT at
                       http://HOST_OR_IP:8080 (default: localhost only).
  --mirror REGISTRY    Pull images through a Docker Hub mirror, e.g.
                       dockerproxy.net, when direct pulls fail.
  --install-docker     Install docker.io and docker-compose-v2 with apt (Ubuntu).
  --admin / --no-admin Create (or skip) the administrator without asking.
  -h, --help           Show this help.
EOF
}

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "==> $*"; }

while (($#)); do
  case "$1" in
    --dataset)
      [[ $# -ge 2 ]] || die "missing directory after --dataset"
      [[ -d "$2" ]] || die "dataset directory not found: $2"
      datasets+=("$(cd -- "$2" && pwd)")
      shift 2
      ;;
    --lan)
      [[ $# -ge 2 ]] || die "missing host after --lan"
      bind_address="0.0.0.0"
      cvat_host="$2"
      shift 2
      ;;
    --mirror)
      [[ $# -ge 2 ]] || die "missing registry after --mirror"
      mirror="${2%/}"
      shift 2
      ;;
    --install-docker) install_docker=1; shift ;;
    --admin) create_admin="yes"; shift ;;
    --no-admin) create_admin="no"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown argument: $1" ;;
  esac
done

[[ -f "${cvat_dir}/docker-compose.yml" ]] || die "cvat/docker-compose.yml is missing from the bundle"

# --- Docker ----------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  if ((install_docker)); then
    command -v apt-get >/dev/null 2>&1 || die "--install-docker only supports apt-based systems"
    info "Installing docker.io and docker-compose-v2 (sudo required)"
    sudo apt-get update
    sudo apt-get install -y docker.io docker-compose-v2
    sudo systemctl enable --now docker
    sudo usermod -aG docker "${USER}"
    echo
    echo "Docker installed. Log out and back in (or run 'newgrp docker'), then rerun:"
    echo "  $0 ${original_args[*]}"
    exit 0
  fi
  die "Docker Engine with the Compose v2 plugin is required. Rerun with --install-docker on Ubuntu, or see https://docs.docker.com/engine/install/"
fi

if ! docker info >/dev/null 2>&1; then
  die "cannot talk to the Docker daemon. Start it with 'sudo systemctl start docker' and make sure ${USER} is in the docker group (sudo usermod -aG docker ${USER}, then log in again)."
fi

compose_version="$(docker compose version --short 2>/dev/null | sed 's/^v//; s/[+-].*//')"
if [[ "$(printf '%s\n%s\n' "${min_compose_version}" "${compose_version}" | sort -V | head -n1)" != "${min_compose_version}" ]]; then
  die "Docker Compose ${compose_version} is too old; ${min_compose_version}+ is required"
fi

if ss -ltn 2>/dev/null | awk '{print $4}' | grep -qE '[:.]8080$' \
    && ! docker ps --format '{{.Names}}' | grep -qx traefik; then
  die "port 8080 is already in use by another program"
fi

# --- Configuration -----------------------------------------------------------
cvat_version="$(sed -n 's/^CVAT_VERSION=//p' "${cvat_dir}/.env")"
cvat_version="${cvat_version:-v2.70.0}"
cat > "${cvat_dir}/.env" <<EOF
CVAT_VERSION=${cvat_version}
CVAT_HOST=${cvat_host}
EOF

override="${cvat_dir}/docker-compose.override.yml"
{
  echo "# Generated by install.sh; rerun install.sh instead of editing by hand."
  echo "services:"
  echo "  traefik:"
  echo "    ports: !override"
  echo "      - \"${bind_address}:8080:8080\""
  if ((${#datasets[@]})); then
    for service in cvat_server cvat_worker_import cvat_worker_export cvat_worker_annotation cvat_worker_chunks; do
      echo "  ${service}:"
      echo "    volumes:"
      for dataset in "${datasets[@]}"; do
        echo "      - \"${dataset}:/home/django/share/$(basename -- "${dataset}"):ro\""
      done
    done
  fi
} > "${override}"

cd -- "${cvat_dir}"
docker compose config --quiet || die "generated compose configuration is invalid"

# --- Images ------------------------------------------------------------------
info "Pulling CVAT ${cvat_version} images (about 3 GB on first install)"
if ! docker compose pull; then
  [[ -n "${mirror}" ]] || die "image pull failed. If Docker Hub is unreachable, rerun with --mirror REGISTRY (e.g. --mirror dockerproxy.net)"
  info "Direct pull failed; retrying through ${mirror}"
  while read -r image; do
    docker image inspect "${image}" >/dev/null 2>&1 && continue
    docker pull "${mirror}/${image}"
    docker tag "${mirror}/${image}" "${image}"
  done < <(docker compose config --images | sort -u)
fi

# --- Start -------------------------------------------------------------------
info "Starting CVAT"
docker compose up -d

info "Waiting for the CVAT server (database migrations can take a few minutes)"
deadline=$((SECONDS + 600))
until curl -fs -o /dev/null -H "Host: ${cvat_host}" http://127.0.0.1:8080/api/server/about; do
  ((SECONDS < deadline)) || die "CVAT did not become ready in 10 minutes; check 'docker compose logs cvat_server' in ${cvat_dir}"
  sleep 5
done

if [[ "${create_admin}" == "ask" ]]; then
  if [[ -t 0 ]]; then
    read -r -p "Create a CVAT administrator account now? [Y/n] " reply
    [[ "${reply}" =~ ^[Nn] ]] && create_admin="no" || create_admin="yes"
  else
    create_admin="no"
  fi
fi
if [[ "${create_admin}" == "yes" ]]; then
  docker exec -it cvat_server bash -ic 'python3 ~/manage.py createsuperuser'
fi

echo
echo "CVAT is running: http://${cvat_host}:8080"
if ((${#datasets[@]})); then
  echo "Connected file share:"
  for dataset in "${datasets[@]}"; do
    echo "  /$(basename -- "${dataset}")  <-  ${dataset}"
  done
fi
echo "Manage it from ${cvat_dir} with: docker compose ps | stop | start | logs -f cvat_server"
